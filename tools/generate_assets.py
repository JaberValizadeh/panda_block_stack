#!/usr/bin/env python3
"""Regenerate the lettered block textures and the OGRE material script.

    ./tools/generate_assets.py

The generated files are checked in, so nobody needs PIL to run the scene -
only to change it. Same arrangement as panda_puzzle/tools/generate_assets.py.

Colours stay the ones blocks.world used before the letters were added (A red,
B green, C blue) so the blocks are still tellable apart at a glance from the
Gazebo camera, where a 45 mm cube's letter is only a few pixels tall. D, E and
F came later, for blocks5.world and blocks6.world; orange, violet and teal are
what is left that is not a near-neighbour of the first three under that
camera's white balance.

The letter is WHITE, which is the whole reason these textures carry the block's
colour as well: the face colour and the glyph have to come from the same image.
The alternative - a coloured cube from <ambient>/<diffuse> in blocks.world with
the glyph textured over it - cannot use a white glyph at all. Gazebo applies
inline colours on top of the script material and OGRE multiplies the two, so a
white glyph comes out the exact hue of the face it sits on and disappears.
Setting `colour_op replace` on the texture unit does not save it either; that was
tried and rendered the glyph as a barely visible tint. So: no inline colour in
the world, everything in the image, and the letters read at any angle.

The cost of that is a single point of failure - see the note on
GAZEBO_RESOURCE_PATH in worlds/blocks.world, since a texture the renderer cannot
find leaves the blocks white AND unlettered.
"""

import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, os.pardir)

TEXTURES = os.path.join(PKG, "media", "materials", "textures")
SCRIPTS = os.path.join(PKG, "media", "materials", "scripts")

SIZE = 256
FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

LETTER = (255, 255, 255)
BORDER = (20, 20, 24)

# letter -> face colour. Saturated enough that the white glyph keeps its contrast
# on the faces the sun does not reach, dark enough that the glyph is the lightest
# thing on the block.
BLOCKS = {
    "A": (200, 40, 40),
    "B": (40, 160, 40),
    "C": (40, 80, 200),
    "D": (210, 120, 20),
    "E": (130, 55, 175),
    "F": (25, 160, 165),
}


def write_textures():
    font = ImageFont.truetype(FONT_PATH, 190)
    for letter, bg in sorted(BLOCKS.items()):
        image = Image.new("RGB", (SIZE, SIZE), bg)
        draw = ImageDraw.Draw(image)
        # A dark border reads as the cube's edge, so the letter still looks
        # like it is painted on a face when two blocks are stacked flush.
        draw.rectangle([0, 0, SIZE - 1, SIZE - 1], outline=BORDER, width=12)
        # anchor="mm" centres the glyph's own bounding box on the point,
        # which is what "in the middle of the face" means. The arithmetic this
        # replaced used draw.textsize(), removed in Pillow 10, and had to carry
        # a hand-tuned nudge to undo that call's excluded top bearing.
        draw.text((SIZE / 2, SIZE / 2), letter, fill=LETTER, font=font,
                  anchor="mm")
        image.save(os.path.join(TEXTURES, "block_%s.png" % letter))
    print("wrote %d textures" % len(BLOCKS))


MATERIAL_HEADER = """\
// Coloured, lettered faces for the blocks - A red, B green, C blue, D orange,
// E violet, F teal, each with a white letter. Generated by
// tools/generate_assets.py.
//
// blocks.world uses A, B and C; blocks5.world adds D and E; blocks6.world
// adds F. A material nothing loads costs nothing, so all six live here.
//
// Referenced from worlds/blocks.world as:
//   <script>
//     <uri>file://media/materials/scripts/blocks.material</uri>
//     <uri>file://media/materials/textures</uri>
//     <name>Blocks/A</name>
//   </script>
// Both URIs are needed: the first finds this script, the second puts the PNGs
// on OGRE's texture search path. They resolve against GAZEBO_RESOURCE_PATH,
// which environment.launch and setup_env.bash both point at the package root.
//
// The texture goes on all six faces, so the letter is readable whichever way
// the block ends up rotated after a grasp.
//
// The colours below are deliberately NEUTRAL: OGRE multiplies them into the
// texture, and the face colour and the white glyph both live in the texture. Tint
// this pass, or state <ambient>/<diffuse> next to the <script> in the world, and
// the glyph is multiplied to the same hue as its face and vanishes.
//
// ambient is a full 1.0 rather than the 0.6 these materials started with. It sets
// how much of the scene's ambient light the face keeps, which is the only light a
// face gets when it is turned away from the sun - at 0.6 the letter on the front
// of a block was legible but grey and dim next to the one on its top. Raising it
// costs nothing at the lit end, since the top faces were nowhere near saturated.
"""

MATERIAL_ENTRY = """
material Blocks/%(letter)s
{
  technique
  {
    pass
    {
      ambient 1.0 1.0 1.0 1.0
      diffuse 1.0 1.0 1.0 1.0
      specular 0.1 0.1 0.1 1.0 12.5

      texture_unit
      {
        texture block_%(letter)s.png
        filtering anisotropic
        max_anisotropy 16
      }
    }
  }
}
"""


def write_material():
    path = os.path.join(SCRIPTS, "blocks.material")
    with open(path, "w") as fh:
        fh.write(MATERIAL_HEADER)
        for letter in sorted(BLOCKS):
            fh.write(MATERIAL_ENTRY % {"letter": letter})
    print("wrote %s" % path)


if __name__ == "__main__":
    for d in (TEXTURES, SCRIPTS):
        if not os.path.isdir(d):
            os.makedirs(d)
    write_textures()
    write_material()
